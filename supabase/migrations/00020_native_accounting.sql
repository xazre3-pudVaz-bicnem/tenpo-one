-- 証憑ファイルの差し替え防止: file_path / content_hash は一度設定したら変更不可
create or replace function public.prevent_document_tamper()
returns trigger language plpgsql as $$
begin
  if old.file_path is not null and new.file_path is distinct from old.file_path then
    raise exception 'DOCUMENT_FILE_IMMUTABLE';
  end if;
  if old.content_hash is not null and new.content_hash is distinct from old.content_hash then
    raise exception 'DOCUMENT_HASH_IMMUTABLE';
  end if;
  return new;
end $$;
create trigger trg_documents_tamper before update on public.documents
  for each row execute function public.prevent_document_tamper();

