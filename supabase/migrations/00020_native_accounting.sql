-- ---- 勘定科目マスター ----
create table public.accounts (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id),
  code text not null,
  name text not null,
  category text not null check (category in ('asset','liability','equity','revenue','expense')),
  sub_type text, -- cash / bank / receivable / payable / inventory 等（出納帳・自動仕訳の対象判定）
  default_tax_treatment text not null default 'taxable_standard' check (default_tax_treatment in
    ('taxable_standard','taxable_reduced','non_taxable','tax_exempt','out_of_scope')),
  is_system boolean not null default false, -- 標準テンプレート由来（削除不可・名称変更可）
  sort_order integer not null default 0,
  status text not null default 'active' check (status in ('active','deleted')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid,
  updated_by uuid,
  unique (organization_id, code)
);
create trigger trg_accounts_updated_at before update on public.accounts
  for each row execute function public.set_updated_at();

