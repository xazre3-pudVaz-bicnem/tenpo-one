-- 仕訳の確定（借方=貸方の検証・締め済み期間の拒否）
create or replace function public.post_journal_entry(p_entry_id uuid)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_entry public.journal_entries%rowtype;
  v_debit bigint;
  v_credit bigint;
  v_lines integer;
begin
  select * into v_entry from public.journal_entries where id = p_entry_id for update;
  if not found then raise exception 'ENTRY_NOT_FOUND'; end if;
  if v_entry.status <> 'draft' then raise exception 'ENTRY_NOT_DRAFT'; end if;
  if not public.app_role_in(v_entry.organization_id,
      array['org_owner','hq_admin','hq_accounting']) then
    raise exception 'FORBIDDEN';
  end if;
  -- 締め済み期間への計上禁止
  if exists (
    select 1 from public.accounting_periods
    where organization_id = v_entry.organization_id
      and month = date_trunc('month', v_entry.entry_date)::date
      and status = 'closed') then
    raise exception 'PERIOD_CLOSED';
  end if;

  select coalesce(sum(amount) filter (where side = 'debit'), 0),
         coalesce(sum(amount) filter (where side = 'credit'), 0),
         count(*)
  into v_debit, v_credit, v_lines
  from public.journal_entry_lines where entry_id = p_entry_id;

  if v_lines < 2 then raise exception 'INSUFFICIENT_LINES'; end if;
  if v_debit <> v_credit then
    raise exception 'UNBALANCED: debit=% credit=%', v_debit, v_credit;
  end if;

  update public.journal_entries
  set status = 'posted', posted_by = auth.uid(), posted_at = now(), updated_by = auth.uid()
  where id = p_entry_id;

  perform public.log_audit(v_entry.organization_id, v_entry.store_id, 'journal.post',
    'journal_entries', p_entry_id::text, null,
    jsonb_build_object('debit', v_debit, 'credit', v_credit, 'source', v_entry.source_type), null);
  return jsonb_build_object('ok', true, 'debit', v_debit, 'credit', v_credit);
end $$;

-- 確定済み仕訳の取消（履歴保持・修正仕訳の起点）
create or replace function public.void_journal_entry(p_entry_id uuid, p_reason text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare v_entry public.journal_entries%rowtype;
begin
  select * into v_entry from public.journal_entries where id = p_entry_id for update;
  if not found then raise exception 'ENTRY_NOT_FOUND'; end if;
  if v_entry.status <> 'posted' then raise exception 'ENTRY_NOT_POSTED'; end if;
  if not public.app_role_in(v_entry.organization_id, array['org_owner','hq_admin','hq_accounting']) then
    raise exception 'FORBIDDEN';
  end if;
  if p_reason is null or length(trim(p_reason)) = 0 then raise exception 'REASON_REQUIRED'; end if;
  if exists (
    select 1 from public.accounting_periods
    where organization_id = v_entry.organization_id
      and month = date_trunc('month', v_entry.entry_date)::date
      and status = 'closed') then
    raise exception 'PERIOD_CLOSED';
  end if;

  update public.journal_entries
  set status = 'voided', void_reason = p_reason, updated_by = auth.uid()
  where id = p_entry_id;
  perform public.log_audit(v_entry.organization_id, v_entry.store_id, 'journal.void',
    'journal_entries', p_entry_id::text, null, jsonb_build_object('reason', p_reason), p_reason);
  return jsonb_build_object('ok', true);
end $$;

-- 月次締め / 締め解除（解除は上位権限+監査ログ）
create or replace function public.close_accounting_period(p_org uuid, p_month date)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
begin
  if not public.app_role_in(p_org, array['org_owner','hq_admin','hq_accounting']) then
    raise exception 'FORBIDDEN';
  end if;
  -- 下書き仕訳が残っている月は締め不可
  if exists (
    select 1 from public.journal_entries
    where organization_id = p_org and status = 'draft'
      and date_trunc('month', entry_date)::date = date_trunc('month', p_month)::date) then
    raise exception 'DRAFT_ENTRIES_REMAIN';
  end if;
  insert into public.accounting_periods (organization_id, month, status, closed_by, closed_at)
  values (p_org, date_trunc('month', p_month)::date, 'closed', auth.uid(), now())
  on conflict (organization_id, month)
  do update set status = 'closed', closed_by = auth.uid(), closed_at = now();
  perform public.log_audit(p_org, null, 'accounting.period_close',
    'accounting_periods', p_month::text, null, null, null);
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.reopen_accounting_period(p_org uuid, p_month date, p_reason text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
begin
  if not public.app_role_in(p_org, array['org_owner','hq_admin']) then
    raise exception 'FORBIDDEN';
  end if;
  if p_reason is null or length(trim(p_reason)) = 0 then raise exception 'REASON_REQUIRED'; end if;
  update public.accounting_periods
  set status = 'open', reopened_by = auth.uid(), reopened_at = now()
  where organization_id = p_org and month = date_trunc('month', p_month)::date;
  perform public.log_audit(p_org, null, 'accounting.period_reopen',
    'accounting_periods', p_month::text, null, jsonb_build_object('reason', p_reason), p_reason);
  return jsonb_build_object('ok', true);
end $$;

