-- 確定済み仕訳の明細変更・削除を禁止（修正は correction 仕訳で行う）
create or replace function public.prevent_posted_line_mutation()
returns trigger language plpgsql as $$
declare v_status text;
begin
  select status into v_status from public.journal_entries
  where id = coalesce(new.entry_id, old.entry_id);
  if v_status = 'posted' then
    raise exception 'POSTED_ENTRY_IMMUTABLE';
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end $$;
create trigger trg_jel_immutable before insert or update or delete on public.journal_entry_lines
  for each row execute function public.prevent_posted_line_mutation();

-- 確定済み仕訳ヘッダの改変禁止（void への遷移と void_reason 以外）
create or replace function public.prevent_posted_entry_mutation()
returns trigger language plpgsql as $$
begin
  if old.status = 'posted' then
    if new.status = 'voided' then
      return new; -- 取消は許可（履歴保持・監査ログはRPC側）
    end if;
    if new.status is distinct from old.status
       or new.entry_date is distinct from old.entry_date
       or new.description is distinct from old.description
       or new.store_id is distinct from old.store_id then
      raise exception 'POSTED_ENTRY_IMMUTABLE';
    end if;
  end if;
  return new;
end $$;
create trigger trg_je_immutable before update on public.journal_entries
  for each row execute function public.prevent_posted_entry_mutation();

