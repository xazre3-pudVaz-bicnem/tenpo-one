-- =============================================================
-- 全店舗のキッチン用プリンターは上下さかさまに取り付けているため、
-- 印字を180度回して出す（2026-09-25 店舗報告「全店で厨房の伝票がさかさまに出る」）。
--
-- レジ（レシート）機はそのまま。レシート・会計伝票は厨房伝票と組み方が違い、
-- upside_down はまだ効かない（必要になったら別で対応する）。
-- 新しく足したプリンターは既定 false なので、必要なら
-- 設定 > プリンター の「上下さかさまに印字する」を入れる。
-- =============================================================
update public.printer_configs
set upside_down = true, updated_at = now()
where usage = 'kitchen'
  and status = 'active';
