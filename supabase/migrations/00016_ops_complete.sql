-- ---- 顧客統合（Merge。重複候補はアプリ側で検出） ----
create or replace function public.merge_customers(p_keep_id uuid, p_merge_id uuid, p_note text default null)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_keep public.customers%rowtype;
  v_merge public.customers%rowtype;
begin
  if p_keep_id = p_merge_id then raise exception 'SAME_CUSTOMER'; end if;
  select * into v_keep from public.customers where id = p_keep_id for update;
  select * into v_merge from public.customers where id = p_merge_id for update;
  if v_keep.id is null or v_merge.id is null then raise exception 'CUSTOMER_NOT_FOUND'; end if;
  if v_keep.organization_id <> v_merge.organization_id then raise exception 'ORG_MISMATCH'; end if;
  if not public.app_role_in(v_keep.organization_id,
      array['org_owner','hq_admin','area_manager','store_manager']) then
    raise exception 'FORBIDDEN';
  end if;

  -- 参照の付替え
  update public.reservations set customer_id = p_keep_id where customer_id = p_merge_id;
  update public.orders set customer_id = p_keep_id where customer_id = p_merge_id;
  update public.customer_notes set customer_id = p_keep_id where customer_id = p_merge_id;
  update public.point_transactions set customer_id = p_keep_id where customer_id = p_merge_id;
  update public.coupon_redemptions set customer_id = p_keep_id where customer_id = p_merge_id;
  -- タグ・同意は重複を除いて移す
  insert into public.customer_tag_links (customer_id, tag_id)
    select p_keep_id, tag_id from public.customer_tag_links where customer_id = p_merge_id
  on conflict (customer_id, tag_id) do nothing;
  delete from public.customer_tag_links where customer_id = p_merge_id;
  delete from public.customer_consents where customer_id = p_merge_id;

  -- 集計・残高の統合
  update public.customers
  set visit_count = v_keep.visit_count + v_merge.visit_count,
      total_spent = v_keep.total_spent + v_merge.total_spent,
      cancel_count = v_keep.cancel_count + v_merge.cancel_count,
      no_show_count = v_keep.no_show_count + v_merge.no_show_count,
      point_balance = v_keep.point_balance + v_merge.point_balance,
      first_visit_at = least(v_keep.first_visit_at, v_merge.first_visit_at),
      last_visit_at = greatest(v_keep.last_visit_at, v_merge.last_visit_at),
      email = coalesce(v_keep.email, v_merge.email),
      name_kana = coalesce(v_keep.name_kana, v_merge.name_kana),
      birthday = coalesce(v_keep.birthday, v_merge.birthday),
      allergy_note = coalesce(v_keep.allergy_note, v_merge.allergy_note),
      updated_by = auth.uid()
  where id = p_keep_id;

  -- 統合元は論理削除（電話番号は重複回避のため退避）
  update public.customers
  set status = 'deleted',
      phone = case when phone is not null then phone || ':merged:' || substr(p_keep_id::text,1,8) end,
      service_note = coalesce(service_note || E'\n', '') || '[統合] ' || p_keep_id::text,
      updated_by = auth.uid()
  where id = p_merge_id;

  perform public.log_audit(v_keep.organization_id, null, 'customer.merge',
    'customers', p_keep_id::text,
    jsonb_build_object('merged_from', p_merge_id,
      'merged_name', v_merge.name, 'merged_phone', v_merge.phone),
    jsonb_build_object('visit_count', v_keep.visit_count + v_merge.visit_count,
      'total_spent', v_keep.total_spent + v_merge.total_spent), p_note);

  return jsonb_build_object('ok', true);
end $$;

-- ---- 打刻厳密化 v2: 休憩中フラグ・休憩中退勤の自動処理 ----
alter table public.time_entries add column on_break boolean not null default false;

create or replace function public.apply_punch(
  p_store_id uuid, p_profile_id uuid, p_event_type text,
  p_source text default 'personal', p_via_pin boolean default false)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_store public.stores%rowtype;
  v_entry public.time_entries%rowtype;
  v_today date := (now() at time zone 'Asia/Tokyo')::date;
  v_last_break public.time_entry_events%rowtype;
  v_break_min integer;
  v_note text := null;
begin
  select * into v_store from public.stores where id = p_store_id;
  if not found then raise exception 'STORE_NOT_FOUND'; end if;
  if p_profile_id <> auth.uid() and not p_via_pin
     and not public.app_role_in(v_store.organization_id,
       array['org_owner','hq_admin','area_manager','store_manager']) then
    raise exception 'FORBIDDEN';
  end if;

  -- 日跨ぎ勤務: 当日にopenが無ければ前日のopenも対象にする
  select * into v_entry from public.time_entries
  where profile_id = p_profile_id and store_id = p_store_id
    and work_date in (v_today, v_today - 1) and status = 'open'
  order by work_date desc, created_at desc limit 1;

  if p_event_type = 'clock_in' then
    if found and v_entry.clock_out_at is null then raise exception 'ALREADY_CLOCKED_IN'; end if;
    -- 他店舗でopenのままなら二重出勤として拒否
    if exists (select 1 from public.time_entries
               where profile_id = p_profile_id and status = 'open' and clock_out_at is null
                 and work_date in (v_today, v_today - 1)) then
      raise exception 'ALREADY_CLOCKED_IN_ELSEWHERE';
    end if;
    insert into public.time_entries
      (organization_id, store_id, profile_id, work_date, clock_in_at, source, created_by)
    values (v_store.organization_id, p_store_id, p_profile_id, v_today, now(), p_source, auth.uid())
    returning * into v_entry;

  elsif p_event_type = 'clock_out' then
    if v_entry.id is null or v_entry.clock_in_at is null then raise exception 'NOT_CLOCKED_IN'; end if;
    if v_entry.on_break then
      -- 休憩中の退勤: 休憩を自動終了して退勤（警告として記録）
      select * into v_last_break from public.time_entry_events
      where time_entry_id = v_entry.id and event_type = 'break_start'
      order by occurred_at desc limit 1;
      if v_last_break.id is not null then
        v_break_min := ceil(extract(epoch from (now() - v_last_break.occurred_at)) / 60)::integer;
        v_note := '休憩未終了のまま退勤（休憩' || v_break_min || '分を自動確定）';
        update public.time_entries
        set break_minutes = break_minutes + v_break_min where id = v_entry.id;
      end if;
    end if;
    update public.time_entries
    set clock_out_at = now(), status = 'closed', on_break = false,
        note = case when v_note is not null
                    then coalesce(note || E'\n', '') || v_note else note end,
        updated_by = auth.uid()
    where id = v_entry.id;

  elsif p_event_type = 'break_start' then
    if v_entry.id is null then raise exception 'NOT_CLOCKED_IN'; end if;
    if v_entry.on_break then raise exception 'ALREADY_ON_BREAK'; end if;
    update public.time_entries set on_break = true where id = v_entry.id;

  elsif p_event_type = 'break_end' then
    if v_entry.id is null then raise exception 'NOT_CLOCKED_IN'; end if;
    if not v_entry.on_break then raise exception 'NOT_ON_BREAK'; end if;
    select * into v_last_break from public.time_entry_events
    where time_entry_id = v_entry.id and event_type = 'break_start'
    order by occurred_at desc limit 1;
    if v_last_break.id is not null then
      v_break_min := ceil(extract(epoch from (now() - v_last_break.occurred_at)) / 60)::integer;
      update public.time_entries
      set break_minutes = break_minutes + v_break_min, on_break = false
      where id = v_entry.id;
    else
      update public.time_entries set on_break = false where id = v_entry.id;
    end if;
  else
    raise exception 'INVALID_EVENT';
  end if;

  insert into public.time_entry_events
    (organization_id, store_id, profile_id, time_entry_id, event_type, source, via_pin)
  values
    (v_store.organization_id, p_store_id, p_profile_id, v_entry.id, p_event_type, p_source, p_via_pin);

  return jsonb_build_object('ok', true, 'entry_id', v_entry.id, 'event', p_event_type,
    'warning', v_note);
end $$;

