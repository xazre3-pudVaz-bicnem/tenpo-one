-- 発送: 送り元在庫を減算（負在庫禁止設定を尊重）
create or replace function public.ship_stock_transfer(p_transfer_id uuid)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_t public.stock_transfers%rowtype;
  v_line record;
  v_item public.inventory_items%rowtype;
  v_allow_negative boolean;
begin
  select * into v_t from public.stock_transfers where id = p_transfer_id for update;
  if not found then raise exception 'TRANSFER_NOT_FOUND'; end if;
  if v_t.status <> 'requested' then raise exception 'INVALID_STATUS'; end if;
  if not public.app_role_in(v_t.organization_id,
      array['org_owner','hq_admin','area_manager','store_manager','assistant_manager']) then
    raise exception 'FORBIDDEN';
  end if;
  select coalesce(allow_negative_stock, true) into v_allow_negative
  from public.store_settings where store_id = v_t.from_store_id;

  for v_line in select * from public.stock_transfer_items where transfer_id = p_transfer_id loop
    select * into v_item from public.inventory_items where id = v_line.inventory_item_id for update;
    if not v_allow_negative and v_item.current_quantity < v_line.quantity then
      raise exception 'INSUFFICIENT_STOCK: %', v_item.name;
    end if;
    insert into public.stock_movements
      (organization_id, store_id, inventory_item_id, movement_type, quantity, unit_cost,
       reason, transfer_group_id, to_store_id, business_date, created_by)
    values
      (v_t.organization_id, v_t.from_store_id, v_item.id, 'transfer_out', -v_line.quantity,
       v_item.avg_cost, '店舗間移動 #' || v_t.transfer_no, v_t.id, v_t.to_store_id,
       public.app_business_date(v_t.from_store_id), auth.uid());
    update public.inventory_items
    set current_quantity = current_quantity - v_line.quantity where id = v_item.id;
  end loop;

  update public.stock_transfers
  set status = 'shipped', shipped_at = now(), shipped_by = auth.uid(), updated_by = auth.uid()
  where id = p_transfer_id;
  perform public.log_audit(v_t.organization_id, v_t.from_store_id, 'inventory.transfer.ship',
    'stock_transfers', p_transfer_id::text, null, null, null);
  return jsonb_build_object('ok', true);
end $$;

-- 受取: 受取店の同名品目へ加算（なければ作成）。発送済みのみ受取可能
create or replace function public.receive_stock_transfer(p_transfer_id uuid)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  v_t public.stock_transfers%rowtype;
  v_line record;
  v_src public.inventory_items%rowtype;
  v_dst public.inventory_items%rowtype;
begin
  select * into v_t from public.stock_transfers where id = p_transfer_id for update;
  if not found then raise exception 'TRANSFER_NOT_FOUND'; end if;
  if v_t.status <> 'shipped' then raise exception 'INVALID_STATUS'; end if;
  if not public.app_role_in(v_t.organization_id,
      array['org_owner','hq_admin','area_manager','store_manager','assistant_manager']) then
    raise exception 'FORBIDDEN';
  end if;

  for v_line in select * from public.stock_transfer_items where transfer_id = p_transfer_id loop
    select * into v_src from public.inventory_items where id = v_line.inventory_item_id;
    select * into v_dst from public.inventory_items
    where organization_id = v_t.organization_id and store_id = v_t.to_store_id
      and name = v_line.name and status = 'active' limit 1;
    if not found then
      insert into public.inventory_items
        (organization_id, store_id, name, item_kind, category, unit,
         current_quantity, reorder_point, avg_cost, menu_item_id,
         purchase_unit, purchase_to_stock_factor, created_by)
      values
        (v_t.organization_id, v_t.to_store_id, v_line.name, v_src.item_kind, v_src.category,
         v_line.unit, 0, v_src.reorder_point, v_src.avg_cost, v_src.menu_item_id,
         v_src.purchase_unit, coalesce(v_src.purchase_to_stock_factor, 1), auth.uid())
      returning * into v_dst;
    end if;
    insert into public.stock_movements
      (organization_id, store_id, inventory_item_id, movement_type, quantity, unit_cost,
       reason, transfer_group_id, business_date, created_by)
    values
      (v_t.organization_id, v_t.to_store_id, v_dst.id, 'transfer_in', v_line.quantity,
       v_src.avg_cost, '店舗間移動 #' || v_t.transfer_no, v_t.id,
       public.app_business_date(v_t.to_store_id), auth.uid());
    update public.inventory_items
    set current_quantity = current_quantity + v_line.quantity where id = v_dst.id;
  end loop;

  update public.stock_transfers
  set status = 'received', received_at = now(), received_by = auth.uid(), updated_by = auth.uid()
  where id = p_transfer_id;
  perform public.log_audit(v_t.organization_id, v_t.to_store_id, 'inventory.transfer.receive',
    'stock_transfers', p_transfer_id::text, null, null, null);
  return jsonb_build_object('ok', true);
end $$;

